    [Fact]
    public void EveryMatrixHasThreeFindersAndDarkModule()
    {
        var code = QrCodeCore.Encode("https://obs-helper.local/m/abc");
        var size = code.Size;
        foreach (var (x, y) in new[] { (0, 0), (size - 7, 0), (0, size - 7) })
        {
            for (var dy = 0; dy < 7; dy++)
            {
                for (var dx = 0; dx < 7; dx++)
                {
                    var expected = dx == 0 || dx == 6 || dy == 0 || dy == 6
                        || (dx is >= 2 and <= 4 && dy is >= 2 and <= 4);
                    Assert.Equal(expected, code.Modules[y + dy][x + dx]);
                }
            }
        }
        Assert.True(code.Modules[size - 8][8], "固定深色模块必须存在");
    }

    [Fact]
    public void TooLongInputFailsExplicitly()
        => Assert.Throws<QrCodeCore.QrTooLongException>(() => QrCodeCore.Encode(new string('a', 400)));

    [Fact]
    public void Utf8ContentFitsAnnouncedCapacity()
    {
        const string text = "配对：OBS帮助助手";
        var code = QrCodeCore.Encode(text);
        var needed = 4 + 8 + System.Text.Encoding.UTF8.GetByteCount(text);
        Assert.True(needed <= QrCodeCore.DataCodewords(code.Version) * 8);
        Assert.True(code.Size >= 21);
    }

    [Fact]
    public void ForcedMaskOutOfRangeFails()
        => Assert.Throws<ArgumentOutOfRangeException>(() => QrCodeCore.Encode("x", 8));

    [Fact]
    public void SvgIsSelfContained()
    {
        var svg = QrCodeCore.ToSvg(QrCodeCore.Encode("https://obs-helper.local/m/abc"));
        Assert.Contains("<svg", svg);
        Assert.DoesNotContain("href", svg);
        Assert.DoesNotContain("<image", svg);
        Assert.DoesNotContain("url(", svg);
        // 唯一的 http 串只能是 SVG 命名空间本身
        Assert.Equal(1, svg.Split("http://").Length - 1);
    }

    [Theory]
    [InlineData(1, 16)]
    [InlineData(4, 64)]
    [InlineData(10, 216)]
    public void DataCodewordTableIsConsistent(int version, int expected)
        => Assert.Equal(expected, QrCodeCore.DataCodewords(version));
